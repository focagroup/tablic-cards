'use strict';
/*
 * Regenerates the Serbian Cyrillic strings (I18N.sr) in app/assets/web/i18n.js from the
 * Serbian Latin ones (I18N.sr_lat). HTML tags, {placeholders}, Wi-Fi, Bluetooth and the card letters
 * J/Q/K stay as they are.   Usage: node tools/sr_cyrillic.js
 */
const fs = require('fs');
const FILE = 'app/assets/web/i18n.js';
const src = fs.readFileSync(FILE, 'utf8');
const I18N = new Function(src.replace(/let LANG[\s\S]*$/, '') + '; return I18N;')();

const DI = {'lj': 'љ', 'nj': 'њ', 'dž': 'џ', 'Lj': 'Љ', 'LJ': 'Љ', 'Nj': 'Њ', 'NJ': 'Њ', 'Dž': 'Џ', 'DŽ': 'Џ'};
const ONE = {a:'а',b:'б',c:'ц',č:'ч',ć:'ћ',d:'д',đ:'ђ',e:'е',f:'ф',g:'г',h:'х',i:'и',j:'ј',k:'к',l:'л',m:'м',n:'н',o:'о',p:'п',r:'р',s:'с',š:'ш',t:'т',u:'у',v:'в',z:'з',ž:'ж'};
for (const k of Object.keys(ONE)) ONE[k.toUpperCase()] = ONE[k].toUpperCase();

function words(text) {
  return text.replace(/(lj|nj|dž|Lj|LJ|Nj|NJ|Dž|DŽ)|([A-Za-zčćđšžČĆĐŠŽ])/g, (m, di, one) => di ? DI[di] : (ONE[one] || one));
}
function translit(s) {
  // keep tags, placeholders and a few foreign tokens untouched
  return s.split(/(<[^>]+>|\{[a-z]+\}|Wi-Fi|Bluetooth|\b[JQK]\b)/).map((part, i) => i % 2 ? part : words(part)).join('');
}

const lines = Object.entries(I18N.sr_lat).map(([k, v]) => {
  const tv = translit(v);
  return k === 'rulesHtml' ? `    ${k}: \`${tv}\`` : `    ${k}: ${JSON.stringify(tv).replace(/^"|"$/g, "'").replace(/\\"/g, '"')}`;
});
const block = `sr: { // generated by tools/sr_cyrillic.js from sr_lat\n${lines.join(',\n')}\n  },`;
const out = src.replace(/sr: (null, \/\/ generated from sr_lat below|\{ \/\/ generated by tools\/sr_cyrillic\.js[\s\S]*?\n  \},)/, block);
if (out === src && !src.includes(block)) throw new Error('sr block not found');
fs.writeFileSync(FILE, out);
console.log('sr strings written');
